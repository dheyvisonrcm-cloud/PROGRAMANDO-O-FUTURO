-- =====================================================================
-- MIGRACAO (PostgreSQL / Neon): novo modelo de missoes
-- Rode SOMENTE se voce JA executou a versao anterior do schema.
-- Se o banco ainda esta vazio de tabelas, use o schema_postgres.sql novo.
-- As tabelas missao e usuario_missao sao recriadas (estavam sem dados).
-- =====================================================================
BEGIN;

ALTER TABLE monumentos ADD COLUMN IF NOT EXISTS cidade VARCHAR(50) NULL;

DROP TABLE IF EXISTS usuario_missao;
DROP TABLE IF EXISTS missao;

CREATE TABLE missao (
    id_missao         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo            VARCHAR(100) NOT NULL UNIQUE,
    descricao_missao  VARCHAR(500) NOT NULL,
    tipo_regra        VARCHAR(30)  NOT NULL,
    pontos_recompensa INT NOT NULL DEFAULT 200,
    CONSTRAINT ck_missao_tipo_regra CHECK (tipo_regra IN ('todos_monumentos','cidades_mesmo_dia'))
);

CREATE TABLE missao_monumento (
    id_missao_monumento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_missao           INT NOT NULL,
    id_monumento        INT NOT NULL,
    CONSTRAINT uq_missao_monumento UNIQUE (id_missao, id_monumento),
    CONSTRAINT fk_mm_missao    FOREIGN KEY (id_missao)    REFERENCES missao (id_missao)        ON DELETE CASCADE,
    CONSTRAINT fk_mm_monumento FOREIGN KEY (id_monumento) REFERENCES monumentos (id_monumento) ON DELETE CASCADE
);

CREATE TABLE usuario_missao (
    id_usuario_missao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        INT NOT NULL,
    id_missao         INT NOT NULL,
    data_conclusao    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_missao UNIQUE (id_usuario, id_missao),
    CONSTRAINT fk_um_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_um_missao  FOREIGN KEY (id_missao)  REFERENCES missao (id_missao)   ON DELETE CASCADE
);

COMMIT;
