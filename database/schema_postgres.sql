-- ---------------------------------------------------------------------
-- BASE
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    senha_hash    VARCHAR(255) NOT NULL,
    pontos_totais INT NOT NULL DEFAULT 0
);

CREATE TABLE monumentos (
    id_monumento        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_monumento      VARCHAR(255) NOT NULL,
    descricao_monumento VARCHAR(255),
    qrcode_hash         VARCHAR(255) NOT NULL UNIQUE,
    pontos              INT NOT NULL DEFAULT 10,
    cidade              VARCHAR(50) NULL,    -- 'Olinda' | 'Recife' (usada nas missoes)
    latitude            DECIMAL(9,6) NULL,   -- RF06
    longitude           DECIMAL(9,6) NULL    -- RF06
    -- fatos_base TEXT NULL                  -- opcional, base de fatos p/ a IA
);

CREATE TABLE brindes (
    brinde_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_monumento INT,
    imagem_url   VARCHAR(255),
    nome_brinde  VARCHAR(255) NOT NULL,
    CONSTRAINT fk_brindes_monumentos FOREIGN KEY (id_monumento)
        REFERENCES monumentos(id_monumento) ON DELETE SET NULL ON UPDATE CASCADE
);

-- UNIQUE garante a regra de "conquista inedita" (RF03/RF04)
CREATE TABLE usuario_conquista (
    id_conquista   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     INT NOT NULL,
    id_monumento   INT NOT NULL,
    data_conquista TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_monumento UNIQUE (id_usuario, id_monumento),
    CONSTRAINT fk_conquista_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_conquista_monumento FOREIGN KEY (id_monumento)
        REFERENCES monumentos(id_monumento) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE usuario_brindes (
    id_usuario_brindes INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brinde_id          INT NOT NULL,
    id_usuario         INT NOT NULL,
    data_resgate       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuario_brindes_brinde FOREIGN KEY (brinde_id)
        REFERENCES brindes(brinde_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_usuario_brindes_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE
    -- Opcional: impedir o mesmo brinde duplicado por usuario
    -- , CONSTRAINT uq_usuario_brinde UNIQUE (id_usuario, brinde_id)
);

-- ---------------------------------------------------------------------
-- TRILHAS E MISSOES (RF08)
-- ---------------------------------------------------------------------
CREATE TABLE trilha (
    id_trilha        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_trilha      VARCHAR(150) NOT NULL,
    descricao_trilha VARCHAR(500) NULL,
    tema             VARCHAR(100) NULL
);

CREATE TABLE trilha_monumento (
    id_trilha_monumento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_trilha           INT NOT NULL,
    id_monumento        INT NOT NULL,
    ordem               INT NOT NULL,
    CONSTRAINT uq_trilha_monumento UNIQUE (id_trilha, id_monumento),
    CONSTRAINT uq_trilha_ordem     UNIQUE (id_trilha, ordem),
    CONSTRAINT fk_tm_trilha    FOREIGN KEY (id_trilha)    REFERENCES trilha (id_trilha)        ON DELETE CASCADE,
    CONSTRAINT fk_tm_monumento FOREIGN KEY (id_monumento) REFERENCES monumentos (id_monumento) ON DELETE CASCADE
);

CREATE TABLE missao (
    id_missao         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo            VARCHAR(100) NOT NULL UNIQUE,
    descricao_missao  VARCHAR(500) NOT NULL,
    tipo_regra        VARCHAR(30)  NOT NULL,
    pontos_recompensa INT NOT NULL DEFAULT 200,
    CONSTRAINT ck_missao_tipo_regra CHECK (tipo_regra IN ('todos_monumentos','cidades_mesmo_dia'))
);

-- Monumentos exigidos por cada missao do tipo 'todos_monumentos'
CREATE TABLE missao_monumento (
    id_missao_monumento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_missao           INT NOT NULL,
    id_monumento        INT NOT NULL,
    CONSTRAINT uq_missao_monumento UNIQUE (id_missao, id_monumento),
    CONSTRAINT fk_mm_missao    FOREIGN KEY (id_missao)    REFERENCES missao (id_missao)        ON DELETE CASCADE,
    CONSTRAINT fk_mm_monumento FOREIGN KEY (id_monumento) REFERENCES monumentos (id_monumento) ON DELETE CASCADE
);

CREATE TABLE usuario_trilha (
    id_usuario_trilha INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        INT NOT NULL,
    id_trilha         INT NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'em_andamento',
    data_inicio       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_conclusao    TIMESTAMP NULL,
    CONSTRAINT ck_ut_status CHECK (status IN ('em_andamento','concluida')),
    CONSTRAINT uq_usuario_trilha UNIQUE (id_usuario, id_trilha),
    CONSTRAINT fk_ut_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_ut_trilha  FOREIGN KEY (id_trilha)  REFERENCES trilha (id_trilha)   ON DELETE CASCADE
);

CREATE TABLE usuario_missao (
    id_usuario_missao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        INT NOT NULL,
    id_missao         INT NOT NULL,
    data_conclusao    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_missao UNIQUE (id_usuario, id_missao),
    CONSTRAINT fk_um_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_um_missao  FOREIGN KEY (id_missao)  REFERENCES missao (id_missao)   ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- NARRATIVAS (RF07) E DIARIO/FAVORITOS (RF09)
-- ---------------------------------------------------------------------
CREATE TABLE narrativa_monumento (
    id_narrativa_monumento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_monumento           INT NOT NULL,
    variante               SMALLINT NOT NULL CHECK (variante >= 0),
    texto_narrativa        VARCHAR(400) NOT NULL,
    desafio                VARCHAR(200) NULL,
    aprovada               BOOLEAN NOT NULL DEFAULT FALSE,
    data_geracao           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_narrativa_variante UNIQUE (id_monumento, variante),
    CONSTRAINT fk_nm_monumento FOREIGN KEY (id_monumento) REFERENCES monumentos (id_monumento) ON DELETE CASCADE
);

CREATE TABLE usuario_favorito (
    id_favorito   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario    INT NOT NULL,
    id_monumento  INT NOT NULL,
    data_favorito TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_favorito UNIQUE (id_usuario, id_monumento),
    CONSTRAINT fk_uf_usuario   FOREIGN KEY (id_usuario)   REFERENCES usuario (id_usuario)       ON DELETE CASCADE,
    CONSTRAINT fk_uf_monumento FOREIGN KEY (id_monumento) REFERENCES monumentos (id_monumento)  ON DELETE CASCADE
);

CREATE TABLE usuario_narrativa (
    id_usuario_narrativa   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario             INT NOT NULL,
    id_narrativa_monumento INT NOT NULL,
    data_salvamento        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuario_narrativa UNIQUE (id_usuario, id_narrativa_monumento),
    CONSTRAINT fk_un_usuario   FOREIGN KEY (id_usuario)             REFERENCES usuario (id_usuario)                          ON DELETE CASCADE,
    CONSTRAINT fk_un_narrativa FOREIGN KEY (id_narrativa_monumento) REFERENCES narrativa_monumento (id_narrativa_monumento) ON DELETE CASCADE
);
